/*
 * Dummy implementations for the cryptography functions that are easier for the
 * fuzzer to get past.
 *
 * We make sure to touch all the input and output bytes the real code would
 * touch so that we trigger out-of-bounds accesses, if any.
 *
 * The return values are data dependent to make sure the accesses dont get
 * optimized out.
 */

int spic_ed25519_verify(const uint8_t *public_key,
                        const uint8_t *signature,
                        const uint8_t *message,
                        size_t message_len)
{
	uint8_t x = 0;

	for (size_t i = 0; i < 32; i++)
		x ^= public_key[i];

	for (size_t i = 0; i < 64; i++)
		x ^= signature[i];

	for (size_t i = 0; i < message_len; i++)
		x ^= message[i];

	if (x & 1)
		return 0;

	return -1;
}

static uint8_t sha_dummy;
void spic_sha256_reset(void)
{
	sha_dummy = 0;
}

void spic_sha256_update(const uint8_t *in, size_t inlen)
{
	for (size_t i = 0; i < inlen; i++)
		sha_dummy ^= in[i];
}

void spic_sha256_finish(uint8_t *out)
{
	memset(out, sha_dummy, 32);
}

void spic_sha256(uint8_t *out, const uint8_t *in, size_t inlen)
{
	spic_sha256_reset();
	spic_sha256_update(in, inlen);
	spic_sha256_finish(out);
}

